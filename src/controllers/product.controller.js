import asyncHandler from "../utils/asyncHandler.js";
import ProductModel from "../models/product.model.js";
import { uploadToImagekit } from "../config/imageKit.js";
import mongoose from "mongoose";
import appError from "../utils/appError.js";

// Check the url is valid or not
const isValidUrl = (value) => {
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
};

/**
 * Create a new product with images
 * @param {Object} req - Express request object with user from auth middleware
 * @param {Object} req.body - Product data (name, description, price, category, imageURLs)
 * @param {Object} res - Express response object
 * @returns {Object} Success message with created product
 * @throws {appError} If validation fails
 */
const createProduct = asyncHandler(async (req, res) => {
  const { name, description, price, category, imageURLs } = req.body;
  const user = req.user;
  let images = [];
  // if image urls exist from generated by frontend then we take it as product images
  if (imageURLs !== undefined && Array.isArray(imageURLs)) {
    // only 5 url should store
    images = imageURLs.slice(0, 5).map(url => isValidUrl(url) ? url : null);
  }
  // Upload each in-memory multer file to ImageKit before storing product data.
  else if (req.files && req.files.length > 0) {
    images = await Promise.all(
      req.files.map((file) => uploadToImagekit(file, user._id)),
    );
  }
  const newProduct = await ProductModel.create({
    name,
    description,
    price,
    category,
    images,
    seller: user._id,
  });

  // Return seller contact basics with the newly created product response.
  const populateProduct = await ProductModel.findById(newProduct._id).populate(
    "seller",
    "name email",
  );
  return res
    .status(201)
    .json({ message: "Product added successfully", product: populateProduct });
});

/**
 * Fetch all products with optional category filter and pagination
 * @param {Object} req - Express request object
 * @param {string} req.query.category - Optional category filter
 * @param {number} req.query.page - Page number (default: 1)
 * @param {number} req.query.limit - Items per page (default: 10, max: 50)
 * @param {Object} res - Express response object
 * @returns {Object} Success message with products array and count
 */
const getAllProducts = asyncHandler(async (req, res) => {
  const { category, page = 1, limit = 10 } = req.query;
  const pageNum = Math.max(1, parseInt(page));
  const limitNum = Math.min(50, Math.max(1, parseInt(limit)));
  const skip = (pageNum - 1) * limitNum;

  // Build a case-insensitive category filter only when the query param exists.
  const query = {};
  if (category) {
    query.category = { $regex: category, $options: "i" };
  }
  const products = await ProductModel.find(query)
    .populate("seller", "name")
    .limit(limitNum)
    .skip(skip);
  const total = await ProductModel.countDocuments(query);

  return res.status(200).json({
    message: "products fetched successfully",
    count: products.length,
    total,
    page: pageNum,
    pages: Math.ceil(total / limitNum),
    products,
  });
});

/**
 * Get all products created by the logged-in user
 * @param {Object} req - Express request object with authenticated user
 * @param {Object} res - Express response object
 * @returns {Object} Success message with user's products
 */
const getMyProducts = asyncHandler(async (req, res) => {
  const products = await ProductModel.find({ seller: req.user._id }).populate(
    "seller",
    "name email",
  );

  res.status(200).json({
    message: "products fetched successfully",
    count: products.length,
    products,
  });
});

/**
 * Get a single product by ID
 * @param {Object} req - Express request object with product ID in params
 * @param {Object} res - Express response object
 * @returns {Object} Success message with product details
 * @throws {appError} If product not found or invalid ID
 */
const getSingleProduct = asyncHandler(async (req, res) => {
  const { id } = req.params;

  // Stop early if the route param cannot be used as a MongoDB ObjectId.
  if (!mongoose.Types.ObjectId.isValid(id))
    throw new appError(400, "invalid product id");

  const product = await ProductModel.findById(id).populate("seller", "name");
  if (!product) throw new appError(404, "Product not found");

  return res
    .status(200)
    .json({ message: "Product found successfully", product });
});

/**
 * Update a product (only the seller can update their own products)
 * @param {Object} req - Express request object with product data and authenticated user
 * @param {Object} res - Express response object
 * @returns {Object} Success message with updated product
 * @throws {appError} If product not found or user not authorized
 */
const updateProduct = asyncHandler(async (req, res) => {
  const { name, description, price, category, imageURLs } = req.body;
  const { id } = req.params;
  let images = [];

  // Validate the id before doing uploads or database work.
  if (!mongoose.Types.ObjectId.isValid(id))
    throw new appError(400, "invalid product id");

  if (imageURLs !== undefined && Array.isArray(imageURLs)) {
    images = imageURLs.slice(0, 5).map(url => isValidUrl(url) ? url : null);
  }
  // New images are optional; when present, they replace the old image list.
  else if (req.files && req.files.length > 0) {
    images = await Promise.all(
      req.files.map((file) => uploadToImagekit(file, req.user._id)),
    );
  }
  
  // Find product and verify seller owns it
  const product = await ProductModel.findOne({ _id: id, seller: req.user._id });
  if (!product) throw new appError(404, "product not found or unauthorized");

  // Only update fields that were provided
  if (name) product.name = name;
  if (description) product.description = description;
  if (price) product.price = price;
  if (category) product.category = category;
  if (images.length > 0) product.images = images;

  await product.save();

  return res
    .status(200)
    .json({ message: "product updated successfully", product });
});
/**
 * Delete a product (only the seller can delete their own products)
 * @param {Object} req - Express request object with product ID and authenticated user
 * @param {Object} res - Express response object
 * @returns {Object} Success message confirming deletion
 * @throws {appError} If product not found or user not authorized
 */
const deleteProduct = asyncHandler(async (req, res) => {
  const { id } = req.params;

  // Check the id format before looking up the product.
  if (!mongoose.Types.ObjectId.isValid(id))
    throw new appError(400, "invalid product ID");

  // Verify seller owns the product before deletion
  const product = await ProductModel.findOne({ _id: id, seller: req.user._id });
  if (!product) throw new appError(404, "product not found or unauthorized");

  await ProductModel.findByIdAndDelete(id);
  return res.status(200).json({ message: "product deleted successfully" });
});

export {
  createProduct,
  getAllProducts,
  getMyProducts,
  getSingleProduct,
  updateProduct,
  deleteProduct,
};
